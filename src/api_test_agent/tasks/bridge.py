"""Bridge approved task cases into regression catalogs (F8 foundation).

Enables approved, human-verified test cases from unified tasks to be registered
and reused directly in the regression test suite (cases.yaml).
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import yaml

from api_test_agent.regression.models import ROOT_PLACEHOLDER
from api_test_agent.tasks.approval import read_approval
from api_test_agent.tasks.store import TaskStore


def export_approved_to_regression_catalog(
    store: TaskStore,
    task_id: str,
    catalog_path: Path,
    *,
    approval_id: str | None = None,
) -> list[dict[str, Any]]:
    """Export frozen approved cases from a task into a regression cases.yaml catalog."""
    task = store.load(task_id)

    if approval_id is None:
        pointer_file = store.folder(task_id) / "active-approval.json"
        if not pointer_file.is_file():
            raise ValueError(f"Task '{task_id}' has no active approved execution selection")
        approval_id = json.loads(pointer_file.read_text("utf-8"))["approval_id"]

    snapshot = read_approval(store, task_id, approval_id)
    op_map = {op.operation_id: op for op in snapshot.inventory.operations}

    today_str = datetime.now(UTC).strftime("%Y-%m-%d")
    project_module = task.target_project or "API"

    exported_entries: list[dict[str, Any]] = []

    for case in snapshot.cases:
        case_apis = []
        for op_id in case.operation_ids:
            if op_id in op_map:
                case_apis.append(op_map[op_id].path)

        # 任务根目录用占位符而不是本机绝对路径：执行时按项目配置 task_root 解析。
        # 子进程 cwd 是被测仓库，相对路径会解析到错误目录，绝对路径又不可移植。
        entry_tokens = [
            "testpilot",
            "task",
            "--root",
            ROOT_PLACEHOLDER,
            "execute",
            task_id,
            "--approval",
            approval_id,
            "--case-id",
            case.case_id,
        ]

        entry_dict = {
            "id": f"TC-{task_id.upper()}-{case.case_id.upper()}",
            "name": case.title,
            "module": project_module,
            "entry": entry_tokens,
            "status": "active",
            "api": sorted(set(case_apis)),
            "notes": (
                f"Generated by TestPilot task '{task_id}', revision {case.revision}, "
                f"approved by {snapshot.actor}"
            ),
            "last_verified": today_str,
            "runner": "task",
            "task_binding": {
                "task_id": task_id,
                "approval_id": approval_id,
                "case_id": case.case_id,
                "revision_hash": case.fingerprint(),
                "execution_kind": case.execution_kind,
                "runner": "task",
                # 只记录变量名：task 子进程按这份白名单从父进程环境取凭据，
                # 凭据值不进入用例目录、配置或日志。
                "credential_env": sorted(snapshot.execution_config.accounts.values()),
            },
        }
        exported_entries.append(entry_dict)

    # Merge into catalog_path with strict safety
    existing_catalog: dict[str, Any] = {"cases": []}
    if catalog_path.is_file():
        try:
            raw_text = catalog_path.read_text("utf-8")
            content = yaml.safe_load(raw_text)
            if content is None:
                content = {"cases": []}
            elif (
                not isinstance(content, dict)
                or "cases" not in content
                or not isinstance(content["cases"], list)
            ):
                raise ValueError(
                    f"Existing catalog {catalog_path} is invalid: "
                    "top-level 'cases' list is required"
                )
            existing_catalog = content
        except Exception as exc:
            raise ValueError(
                f"Refusing to overwrite: failed to parse existing catalog at {catalog_path}: {exc}"
            ) from exc

    existing_cases = existing_catalog.get("cases", [])
    merged_cases = []
    new_ids = {e["id"] for e in exported_entries}

    for c in existing_cases:
        if isinstance(c, dict) and c.get("id") not in new_ids:
            merged_cases.append(c)

    merged_cases.extend(exported_entries)
    existing_catalog["cases"] = merged_cases

    catalog_path.parent.mkdir(parents=True, exist_ok=True)
    catalog_path.write_text(
        yaml.safe_dump(existing_catalog, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )

    return exported_entries
